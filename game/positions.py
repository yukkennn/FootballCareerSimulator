LEFT_SIDE, RIGHT_SIDE = ("LB", "LM", "LW"), ("RB", "RM", "RW")

def height_offsets(pos, height):
    """Сдвиги характеристик от роста относительно типичного для позиции (до нормировки: общий рейтинг почти не меняется,
    меняется профиль). Высокий: сильнее физика (и отбор у защитников), медленнее и хуже дриблинг. Невысокий - наоборот.
    Вратарь: высокий лучше на выходах и в прыжке, хуже в скорости."""
    dh = max(-20, min(20, height - TYPICAL_HEIGHT[pos]))
    if pos == "GK":                                   # DIV HAN KIC REF SPD POS
        return [0.10 * dh, 0.0, 0.0, -0.04 * dh, -0.15 * dh, 0.15 * dh]
    defend = 0.12 * dh if GROUP[pos] == "DEF" or pos == "CDM" else 0.0
    return [-0.15 * dh, 0.0, 0.0, -0.15 * dh, defend, 0.28 * dh]   # PAC SHO PAS DRI DEF PHY

def style_mult(pos, foot, height):
    """Множители (голы, передачи) от ведущей ноги и роста.
    Фланг: игрок «на свою ногу» (левша слева) чаще навешивает -> больше передач; «перевёрнутый» (правша слева) смещается в центр
    и бьёт -> больше голов. Обе ноги: понемногу и того и другого, без крайностей. В центре поля нога на статистику не влияет.
    Рост: высокие нападающие и центральные защитники забивают больше головой, невысокие нападающие - меньше."""
    g = a = 1.0
    if pos in LEFT_SIDE + RIGHT_SIDE:
        natural = (pos in LEFT_SIDE) == (foot == "L")
        if foot == "B":
            g, a = 1.04, 1.04
        elif natural:
            g, a = 0.94, 1.10 if pos not in ("LB", "RB") else 1.12
        else:
            g, a = 1.10 if pos not in ("LB", "RB") else 1.05, 0.95
    if pos in ("ST", "CF", "CB", "CDM"):
        g *= max(0.9, min(1.15, 1 + 0.008 * (height - TYPICAL_HEIGHT[pos])))
    return round(g, 3), round(a, 3)
